const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const themesDir = path.join(root, 'themes');
const outCss = path.join(root, 'assets', 'themes.css');
const outRegistry = path.join(root, 'src', 'themes', 'registry.json');

// A theme must at least define the colors. Everything else falls back to base.css.
const REQUIRED = [
  '--c-bg', '--c-surface', '--c-surface-2', '--c-ink', '--c-muted',
  '--c-line', '--c-accent', '--c-accent-ink', '--c-ok', '--c-bad',
];

function fail(message) {
  console.error(`build-themes: ${message}`);
  process.exit(1);
}

const folders = fs
  .readdirSync(themesDir, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const chunks = ['/* GENERATED by scripts/build-themes.js. Do not edit by hand. */'];
const registry = [];

for (const id of folders) {
  const dir = path.join(themesDir, id);
  const manifestPath = path.join(dir, 'theme.json');
  const cssPath = path.join(dir, 'theme.css');

  if (!/^[a-z0-9-]+$/.test(id)) fail(`folder "${id}" must use a-z, 0-9 and - only`);
  if (!fs.existsSync(manifestPath) || !fs.existsSync(cssPath)) {
    fail(`themes/${id} needs theme.json and theme.css`);
  }

  const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (manifest.id !== id) fail(`themes/${id}/theme.json: id must be "${id}"`);
  if (!manifest.name) fail(`themes/${id}/theme.json: name is required`);
  if (!['light', 'dark'].includes(manifest.mode)) fail(`themes/${id}/theme.json: mode must be light or dark`);

  const css = fs.readFileSync(cssPath, 'utf8');
  if (!css.includes(':theme')) fail(`themes/${id}/theme.css must contain :theme`);
  for (const token of REQUIRED) {
    if (!css.includes(`${token}:`)) fail(`themes/${id}/theme.css is missing ${token}`);
  }

  const scope = `[data-theme='${id}']`;
  chunks.push(
    `/* ---- ${manifest.name} ---- */`,
    `${scope} { color-scheme: ${manifest.mode}; }`,
    css.replaceAll(':theme', scope).trim(),
    '',
  );
  registry.push({ id, name: manifest.name, mode: manifest.mode, description: manifest.description ?? '' });
}

if (!registry.some((theme) => theme.id === 'paper')) fail('the default theme "paper" is missing');

fs.mkdirSync(path.dirname(outCss), { recursive: true });
fs.writeFileSync(outCss, chunks.join('\n'));
fs.writeFileSync(outRegistry, JSON.stringify(registry, null, 2));

console.log(`Built ${registry.length} theme(s): ${registry.map((t) => t.id).join(', ')}`);
